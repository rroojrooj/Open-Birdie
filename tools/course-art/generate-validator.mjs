import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '..', '..');
const SOURCE_SCHEMA_PATH = path.join(REPO, 'lib', 'schemas', 'course-art-source.schema.json');
const RUNTIME_SCHEMA_PATH = path.join(REPO, 'lib', 'schemas', 'course-art-runtime.schema.json');
const DEFAULT_OUTPUT = path.join(REPO, 'lib', 'generated', 'course-art-pack-validator.js');

function parseOutput(argv) {
  const index = argv.indexOf('--output');
  if (index === -1) return DEFAULT_OUTPUT;
  if (!argv[index + 1] || index + 2 !== argv.length) {
    throw new Error('Usage: generate-validator.mjs [--output <file>]');
  }
  return path.resolve(argv[index + 1]);
}

function loadSchema(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

export async function generateValidatorBytes() {
  const sourceSchema = loadSchema(SOURCE_SCHEMA_PATH);
  const runtimeSchema = loadSchema(RUNTIME_SCHEMA_PATH);
  const ajv = new Ajv({
    allErrors: true,
    strict: true,
    strictNumbers: true,
    code: { source: true, lines: true },
  });
  ajv.addSchema(sourceSchema);
  ajv.addSchema(runtimeSchema);

  const schemaRefs = {
    validateSourceIndex: `${sourceSchema.$id}#/$defs/index`,
    validateSourceProfile: `${sourceSchema.$id}#/$defs/profile`,
    validateSourceReferences: `${sourceSchema.$id}#/$defs/references`,
    validateSourceLandmarks: `${sourceSchema.$id}#/$defs/landmarks`,
    validateSourceVegetation: `${sourceSchema.$id}#/$defs/vegetation`,
    validateSourceTerrainFeatures: `${sourceSchema.$id}#/$defs/terrainFeatures`,
    validateRuntimeIndex: `${runtimeSchema.$id}#/$defs/index`,
    validateRuntimeManifest: `${runtimeSchema.$id}#/$defs/manifest`,
  };
  for (const [name, schemaRef] of Object.entries(schemaRefs)) {
    if (!ajv.getSchema(schemaRef)) throw new Error(`Unable to compile ${name}`);
  }

  const standalone = standaloneCode(ajv, schemaRefs);
  const result = await build({
    stdin: {
      contents: standalone,
      loader: 'js',
      resolveDir: REPO,
      sourcefile: 'course-art-pack-validator.generated.cjs',
    },
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: ['node22'],
    write: false,
    minify: false,
    legalComments: 'none',
    sourcemap: false,
    charset: 'utf8',
    banner: {
      js: "'use strict';\n// Generated by tools/course-art/generate-validator.mjs. Do not edit.",
    },
  });
  // Ajv runtime helpers carry generator-only `.code = 'require(...)'` string
  // metadata. It is not executed, but removing it keeps the shipped artifact
  // unambiguously import-free under text and static checks.
  const text = result.outputFiles[0].text.replace(
    /^\s*[A-Za-z_$][\w$]*\.code = ["']require\([^;\r\n]+;\r?\n/gm,
    '',
  );
  const runtimeImport = text.match(/\brequire\s*\(\s*["'][^.]|import\s*\(/);
  if (runtimeImport) {
    throw new Error('Generated validator contains a bare runtime import');
  }
  const bytes = Buffer.from(text);
  return bytes;
}

export async function main(argv = process.argv.slice(2)) {
  const output = parseOutput(argv);
  const bytes = await generateValidatorBytes();
  fs.mkdirSync(path.dirname(output), { recursive: true });
  fs.writeFileSync(output, bytes);
  return { output, bytes: bytes.length };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch((error) => {
    process.stderr.write(`${error.stack || error}\n`);
    process.exitCode = 1;
  });
}
